  const CopySheetEntry({
    required this.stage,
    required this.body,
    this.media = '',
    this.button = '',
    this.leadsTo = '',
  });

  final String stage;
  final String body;
  final String media;
  final String button;
  final String leadsTo;

  List<Object?> toCells() => <Object?>[stage, body, media, button, leadsTo];
}

final class CopySheetParseResult {
  const CopySheetParseResult({required this.rowCount, this.error});

  final int rowCount;
  final String? error;

  bool get isEmpty => rowCount == 0;
}

abstract final class CopySheetParser {
  static const Map<String, String> headerAliases = <String, String>{
    CopySheet.stage: CopySheet.stage,
    'этап': CopySheet.stage,
    'когда': CopySheet.stage,
    CopySheet.body: CopySheet.body,
    'текст сообщения': CopySheet.body,
    'текст': CopySheet.body,
    'письмо': CopySheet.body,
    CopySheet.media: CopySheet.media,
    'вложение': CopySheet.media,
    'картинка': CopySheet.media,
    CopySheet.button: CopySheet.button,
    'кнопка под сообщением': CopySheet.button,
    'кнопка': CopySheet.button,
    CopySheet.leadsTo: CopySheet.leadsTo,
    'куда ведет кнопка': CopySheet.leadsTo,
    'куда ведёт кнопка': CopySheet.leadsTo,
    'куда': CopySheet.leadsTo,
  };

  static String? canonicalHeader(Object? cell) {
    final normalized = _normalizeHeader(cell);
    if (normalized == null) {
      return null;
    }
    return headerAliases[normalized];
  }

  static int? headerRowIndex(List<List<Object?>> rows) {
    for (var i = 0; i < rows.length; i++) {
      final index = headerIndexMap(rows[i]);
      if (index.containsKey(CopySheet.stage) && index.containsKey(CopySheet.body)) {
        return i;
      }
    }
    return null;
  }

  static Map<String, int> headerIndexMap(List<Object?> row) {
    final out = <String, int>{};
    for (var i = 0; i < row.length; i++) {
      final canonical = canonicalHeader(row[i]);
      if (canonical == null || out.containsKey(canonical)) {
        continue;
      }
      out[canonical] = i;
    }
    return out;
  }

  static CopySheetParseResult parse(List<List<Object?>> rows) {
    final headerAt = headerRowIndex(rows);
    if (headerAt == null) {
      return const CopySheetParseResult(rowCount: 0);
    }
    final index = headerIndexMap(rows[headerAt]);
    var count = 0;
    for (var i = headerAt + 1; i < rows.length; i++) {
      final stage = cellOf(rows[i], index, CopySheet.stage);
      if (stage == null || stage.isEmpty) {
        continue;
      }
      count += 1;
    }
    return CopySheetParseResult(rowCount: count);
  }

  static String? cellOf(List<Object?> row, Map<String, int> headerIndex, String column) {
    final at = headerIndex[column];
    if (at == null || at >= row.length) {
      return null;
    }
    final value = row[at];
    if (value == null) {
      return null;
    }
    final text = value.toString().trim();
    return text.isEmpty ? null : text;
  }

  static String? _normalizeHeader(Object? cell) {
    if (cell == null) {
      return null;
    }
    final text = cell.toString().trim().toLowerCase();
    if (text.isEmpty) {
      return null;
    }
    return text.replaceAll(RegExp(r'\s+'), ' ');
  }
}
