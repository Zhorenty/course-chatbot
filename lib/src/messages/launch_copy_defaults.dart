  static Map<LaunchCopySlotKey, StoredTelegramMessage> seedPayload() {
    final slots = <LaunchCopySlotKey, StoredTelegramMessage>{};
    for (final slot in LaunchCopySlotKey.values) {
      if (!slot.storesInCopyTable) {
        continue;
      }
      slots[slot] = storedCopyFromHtml(
        htmlOf(slot),
        photoPaths: FunnelMedia.pathsFor(slot.funnelMediaKey ?? ''),
      );
    }
    return slots;
  }

